import pino, { type DestinationStream, type LoggerOptions } from "pino";

export const createLogger = (
  options: LoggerOptions = {},
  destination?: DestinationStream,
) => {
  const loggerOptions: LoggerOptions = {
    ...options,
    level: options.level ?? process.env.LOG_LEVEL ?? "info",
    redact: {
      paths: [
        "password",
        "token",
        "accessToken",
        "refreshToken",
        "resetToken",
        "verificationToken",
        "authToken",
        "bearerToken",
        "idToken",
        "sessionToken",
        "authorization",
        "cookie",
        "secret",
        "client_secret",
        "apiKey",
        "api_key",
        "*.password",
        "*.currentPassword",
        "*.newPassword",
        "*.token",
        "*.accessToken",
        "*.refreshToken",
        "*.resetToken",
        "*.verificationToken",
        "*.authToken",
        "*.bearerToken",
        "*.idToken",
        "*.sessionToken",
        "*.access_token",
        "*.refresh_token",
        "*.id_token",
        "*.session_token",
        "*.authorization",
        "*.headers.authorization",
        "*.headers.cookie",
        '*.headers["set-cookie"]',
        '*.headers["x-internal-key"]',
        '*.headers["x-gateway-key"]',
        "*.secret",
        "*.client_secret",
        "*.apiKey",
        "*.api_key",
        "req.headers.authorization",
        "req.headers.cookie",
        'req.headers["x-internal-key"]',
        'req.headers["x-gateway-key"]',
        "req.body.password",
        "req.body.token",
        'res.headers["set-cookie"]',
      ],
      censor: "[REDACTED]",
    },
  };
  return destination ? pino(loggerOptions, destination) : pino(loggerOptions);
};
